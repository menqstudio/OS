/// The audit signer's PUBLISHED identity: a key id and a public half, and nothing else.
///
/// Parsed out of the custody record the signer service writes into its own protected
/// directory. The fields it does not read are the point — this type cannot carry a seed,
/// so a custody record that leaked one could not smuggle it into the registry through
/// here (and `brops_audit_signer::custody::read_custody` refuses such a record outright
/// on the reading side).
pub struct AnchorKey {
    pub key_id: String,
    pub public_key: String,
}

impl AnchorKey {
    /// Read `{key_id, public_key, authority}` out of a published custody record.
    ///
    /// The `authority` field must say `audit-anchor`. Registering a key under an
    /// authority its own publisher never claimed would be this module choosing what the
    /// signer's key is for, which is exactly the decision it must not make.
    pub fn from_custody(record: &Value) -> Result<AnchorKey, ProvisionError> {
        let key_id = match record.get("key_id").and_then(Value::as_str) {
            Some(s) if !s.is_empty() => s.to_string(),
            _ => return corrupt("the audit signer's custody record has no key_id", "missing"),
        };
        let public_key = match record.get("public_key").and_then(Value::as_str) {
            Some(s) => s.to_string(),
            None => {
                return corrupt("the audit signer's custody record has no public_key", "missing")
            }
        };
        if public_key.len() != 64 || !public_key.bytes().all(|b| b.is_ascii_hexdigit()) {
            return corrupt(
                "the audit signer's custody record does not carry a 32-byte Ed25519 public key",
                format!("got {} characters", public_key.len()),
            );
        }
        if record.get("authority").and_then(Value::as_str) != Some(audit_signer::ANCHOR_AUTHORITY)
        {
            return corrupt(
                "the audit signer's custody record does not claim the audit-anchor authority",
                format!(
                    "registering it would grant the key an authority its own publisher never \
                     claimed (got {:?})",
                    record.get("authority")
                ),
            );
        }
        if record.get("private_key").is_some() || record.get("seed").is_some() {
            return corrupt(
                "the audit signer's custody record carries secret material",
                "a published record must contain the public half only; a record with a seed in \
                 it means the signer's private half has already escaped its own account",
            );
        }
        Ok(AnchorKey { key_id, public_key })
    }
}

/// One registry entry, in the shape `bro_signature._parse_key` demands.
fn registry_entry(
    key_id: &str,
    public_key: &str,
    authority: &str,
    issued_by: &str,
    provenance: Option<&str>,
) -> Value {
    let mut entry = Map::new();
    entry.insert("key_id".into(), json!(key_id));
    entry.insert("public_key".into(), json!(public_key));
    entry.insert("authority_type".into(), json!(authority));
    // For `audit-anchor` this is deliberately EMPTY and must be: the authority binds no
    // registry artifact type, so `_parse_key` refuses any grant given to it — including
    // `audit-head` itself, which is out-of-registry. Its whole power is the hardcoded
    // `bro_audit_log.ANCHOR_AUTHORITIES` comparison, which is why writing the registry
    // cannot widen what the key is for.
    entry.insert("allowed_artifact_types".into(), json!(artifacts_for(authority)));
    entry.insert("not_before_epoch".into(), json!(NOT_BEFORE_EPOCH));
    entry.insert("not_after_epoch".into(), json!(NEVER_EXPIRES_EPOCH));
    entry.insert("status".into(), json!("active"));
    entry.insert("issued_by".into(), json!(issued_by));
    if let Some(subject) = subject_agent_id(authority) {
        entry.insert("subject_agent_id".into(), json!(subject));
    }
    if let Some(note) = provenance {
        entry.insert("provenance".into(), json!(note));
    }
    Value::Object(entry)
}

fn registry_payload(
    keys: &[AuthorityKey],
    operator: &AuthorityKey,
    anchor: Option<&AnchorKey>,
    now: i64,
) -> Value {
    let mut entries: Vec<Value> = keys
        .iter()
        .map(|key| {
            registry_entry(
                &key.key_id,
                &key.public_key_hex(),
                &key.authority_type,
                &operator.key_id,
                None,
            )
        })
        .collect();
    // The operator's own entry — its PUBLIC half. `load_trusted_keys` refuses a registry
    // that does not contain its own signer, and the entry is what downstream verifiers
    // resolve `conductor-session` signatures through. The private half it was signed with
    // is destroyed a few lines after this payload is signed, which the provenance note
    // says in the document itself rather than only in this comment.
    entries.push(registry_entry(
        &operator.key_id,
        &operator.public_key_hex(),
        OPERATOR,
        &operator.key_id,
        Some(
            "minted in memory at install, signed this registry and the conductor session, \
             and destroyed before provisioning returned: no file in this store carries the \
             private half, so this registry can never be re-signed and no key can ever be \
             added to it",
        ),
    ));
    if let Some(anchor) = anchor {
        entries.push(registry_entry(
            &anchor.key_id,
            &anchor.public_key,
            audit_signer::ANCHOR_AUTHORITY,
            &operator.key_id,
            Some(
                "minted by the audit signer principal on its own first start; this registry \
                 never held the private half, and the operator root that admitted it no longer \
                 exists",
            ),
        ));
    }
    entries.sort_by(|a, b| {
        a["key_id"].as_str().unwrap_or("").cmp(b["key_id"].as_str().unwrap_or(""))
    });

    json!({
        "schema": SCHEMA,
        "artifact_type": "trusted-key-registry",
        "operator_public_key": operator.public_key_hex(),
        "issued_at_epoch": now,
        "registry_version": REGISTRY_VERSION,
        // `load_trusted_keys` refuses a registry that is not marked production whenever
        // the operator pin comes from the production `BRO_OPERATOR_ROOT_PUBKEY_FILE`
        // path, which is the only pin path this deployment has. The marking is true in
        // the sense that check is about — these are not `broctl` development keys shared
        // out of a repository — and not in the sense a fleet operator would mean: the
        // private halves live on this machine. `provenance` and `posture` say which, in
        // the signed payload itself, so no reader has to infer it.
        "production": true,
        "provenance": "locally-minted-at-install",
        "posture": POSTURE_SUMMARY,
        "keys": entries,
    })
}

