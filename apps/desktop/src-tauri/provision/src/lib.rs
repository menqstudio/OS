/// What was actually done to restrict access, per platform. Reported rather than
/// assumed, because the honest answer differs by platform and a caller that printed
/// "owner only" everywhere would be making a claim this code cannot support off unix.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Protection {
    /// POSIX: an explicit `chmod` to the stated mode.
    PosixMode(u32),
    /// Everywhere else: whatever the containing directory grants. On Windows the app
    /// data directory is per-user by default ACL, so key material is not world
    /// readable — but no explicit ACL was applied by this process, and this value says
    /// so instead of implying one was.
    InheritedFromParent { platform: &'static str },
}

impl std::fmt::Display for Protection {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Protection::PosixMode(m) => write!(f, "posix: chmod {m:04o} applied by this process"),
            Protection::InheritedFromParent { platform } => write!(
                f,
                "{platform}: NO explicit permission was applied by this process — \
                 `secure_data_dir`/`secure_owner_only_file` have no non-unix branch, so key \
                 material carries the access control the application data directory grants it \
                 (per-user by default on Windows, plus SYSTEM and Administrators)"
            ),
        }
    }
}

/// Restrict a directory to the owner (0700).
///
/// This is the routine `apps/desktop/src-tauri/src/lib.rs` has always called before
/// opening the database; it lives here so there is exactly one copy and both the host
/// and the provisioner use it.
#[cfg(unix)]
pub fn secure_data_dir(dir: &Path) -> std::io::Result<()> {
    use std::os::unix::fs::PermissionsExt;
    std::fs::set_permissions(dir, std::fs::Permissions::from_mode(0o700))
}
#[cfg(not(unix))]
pub fn secure_data_dir(_dir: &Path) -> std::io::Result<()> {
    Ok(())
}

/// Restrict a single file to the owner (0600). Same per-OS shape as
/// [`secure_data_dir`]; the host's `secure_db_files` calls this too, so the database
/// sidecars and the private keys are restricted by one implementation.
#[cfg(unix)]
pub fn secure_owner_only_file(path: &Path) -> std::io::Result<()> {
    use std::os::unix::fs::PermissionsExt;
    std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o600))
}
#[cfg(not(unix))]
pub fn secure_owner_only_file(_path: &Path) -> std::io::Result<()> {
    Ok(())
}

pub fn directory_protection() -> Protection {
    if cfg!(unix) {
        Protection::PosixMode(0o700)
    } else {
        Protection::InheritedFromParent { platform: platform_name() }
    }
}

pub fn key_file_protection() -> Protection {
    if cfg!(unix) {
        Protection::PosixMode(0o600)
    } else {
        Protection::InheritedFromParent { platform: platform_name() }
    }
}

pub fn platform_name() -> &'static str {
    if cfg!(target_os = "windows") {
        "windows"
    } else if cfg!(target_os = "macos") {
        "macos"
    } else if cfg!(target_os = "linux") {
        "linux"
    } else if cfg!(unix) {
        "unix"
    } else {
        "unknown"
    }
}

