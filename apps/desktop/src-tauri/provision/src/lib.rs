/// One authority's keypair, in the on-disk form `broctl sign --key` also reads
/// (`private_key` is the raw 32-byte Ed25519 seed as hex — the same bytes
/// `Ed25519PrivateKey.private_bytes_raw()` produces on the Python side).
pub struct AuthorityKey {
    pub authority_type: String,
    pub key_id: String,
    pub signing: SigningKey,
}

impl AuthorityKey {
    pub fn public_key_hex(&self) -> String {
        hex(self.signing.verifying_key().as_bytes())
    }

    fn to_json(&self) -> Value {
        let mut value = json!({
            "key_id": self.key_id,
            "authority_type": self.authority_type,
            "private_key": hex(self.signing.as_bytes()),
            "public_key": self.public_key_hex(),
            "production": true,
            "provenance": "minted on this machine at first launch; see POSTURE.txt",
        });
        if let Some(subject) = subject_agent_id(&self.authority_type) {
            value.as_object_mut().unwrap().insert("subject_agent_id".into(), json!(subject));
        }
        value
    }
}

fn mint_key(authority: &str, install_id: &str) -> Result<AuthorityKey, ProvisionError> {
    let mut seed = random_seed()?;
    let key = AuthorityKey {
        authority_type: authority.to_string(),
        key_id: format!("brops-{install_id}-{authority}"),
        signing: SigningKey::from_bytes(&seed),
    };
    wipe(&mut seed);
    Ok(key)
}

