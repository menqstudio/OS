//! First-launch trust provisioning.
//!
//! # What this is, and what it honestly claims
//!
//! BroPS is a single-user desktop application. The owner installs it and everything
//! must already be done: no ceremony, no USB, no key to carry, no annual renewal,
//! nothing to run by hand, ever. So the trust material the engine's governance chain
//! requires — an operator-root keypair, the six other authority keypairs, the
//! operator-signed `trusted-key-registry`, the out-of-registry operator-root pin, and
//! the operator-signed artifacts the residual engine items name — is **minted on the
//! user's own machine, on first launch, by this module**.
//!
//! ## The posture, stated plainly (read this before trusting anything below)
//!
//! Trust material minted on the user's machine at install time protects against an
//! attacker who arrives **later**. It does **not** protect against one who already
//! owns the machine at install time — that attacker witnesses the mint, or performs
//! it. This is the normal, honest posture for locally-minted trust material: an SSH
//! host key works exactly the same way, and so does a TLS private key generated by an
//! installer. Everything downstream inherits that boundary:
//!
//! * The operator-root **private** key lives on the same disk as the process that
//!   uses it, under the same user account. `engine/runtime/bro_signature.py` calls
//!   this out by name — an anchor its reader can rewrite is not an anchor — and
//!   refuses such a pin unless the deployment sets
//!   `BRO_OPERATOR_ROOT_PIN_SELF_OWNED=acknowledged`. This deployment genuinely has
//!   no second principal to offer, so that is what it must set, which does not make
//!   the anchor stronger: it makes the weakness explicit and reportable instead of
//!   silent.
//! * Consequently the chain proves **integrity over time on one machine** (nothing was
//!   swapped after install; a registry cannot be replayed below its floor; a builder
//!   key cannot sign a verifier receipt), not **provenance from a vendor**. No claim
//!   of the second kind may be made on the strength of this module.
//!
//! `POSTURE.txt`, written beside the trust store, says the same thing to whoever finds
//! the directory without this source in front of them.
//!
//! # Properties
//!
//! * **Idempotent.** A second launch VERIFIES what is on disk and returns; it never
//!   re-mints over a working install. See [`verify_existing`].
//! * **Never half-provisioned.** The mint happens in a staging directory that is
//!   renamed into place as the last step. A failure anywhere removes the staging
//!   directory and returns an error naming what failed; a rename that loses a race
//!   against a concurrent instance falls back to verification.
//! * **Byte-compatible with the Python verifier.** Every signature is Ed25519 over
//!   [`canonical::canonical_bytes`], which reproduces `bro_signature.canonical_bytes`
//!   exactly. Proven by `tests/python_verifier.rs`, which runs the REAL
//!   `bro_signature` / `bro_deploy_preflight` against the REAL output of this module.
//! * **Cross-platform**, with the platform difference reported rather than skipped:
//!   see [`Protection`].

pub mod anchor;

pub mod canonical;

