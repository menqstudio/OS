fn registry_payload(keys: &[AuthorityKey], operator: &AuthorityKey, now: i64) -> Value {
    let mut entries: Vec<Value> = keys
        .iter()
        .map(|key| {
            let mut entry = Map::new();
            entry.insert("key_id".into(), json!(key.key_id));
            entry.insert("public_key".into(), json!(key.public_key_hex()));
            entry.insert("authority_type".into(), json!(key.authority_type));
            entry.insert(
                "allowed_artifact_types".into(),
                json!(artifacts_for(&key.authority_type)),
            );
            entry.insert("not_before_epoch".into(), json!(NOT_BEFORE_EPOCH));
            entry.insert("not_after_epoch".into(), json!(NEVER_EXPIRES_EPOCH));
            entry.insert("status".into(), json!("active"));
            entry.insert("issued_by".into(), json!(operator.key_id));
            if let Some(subject) = subject_agent_id(&key.authority_type) {
                entry.insert("subject_agent_id".into(), json!(subject));
            }
            Value::Object(entry)
        })
        .collect();
    entries.sort_by(|a, b| {
        a["key_id"].as_str().unwrap_or("").cmp(b["key_id"].as_str().unwrap_or(""))
    });

    json!({
        "schema": SCHEMA,
        "artifact_type": "trusted-key-registry",
        "operator_public_key": operator.public_key_hex(),
        "issued_at_epoch": now,
        "registry_version": REGISTRY_VERSION,
        // `load_trusted_keys` refuses a registry that is not marked production whenever
        // the operator pin comes from the production `BRO_OPERATOR_ROOT_PUBKEY_FILE`
        // path, which is the only pin path this deployment has. The marking is true in
        // the sense that check is about — these are not `broctl` development keys shared
        // out of a repository — and not in the sense a fleet operator would mean: the
        // private halves live on this machine. `provenance` and `posture` say which, in
        // the signed payload itself, so no reader has to infer it.
        "production": true,
        "provenance": "locally-minted-at-install",
        "posture": POSTURE_SUMMARY,
        "keys": entries,
    })
}

