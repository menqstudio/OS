pub fn hex(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        s.push(char::from_digit((b >> 4) as u32, 16).unwrap());
        s.push(char::from_digit((b & 0x0f) as u32, 16).unwrap());
    }
    s
}

pub fn unhex(s: &str) -> Option<Vec<u8>> {
    if s.len() % 2 != 0 {
        return None;
    }
    let mut out = Vec::with_capacity(s.len() / 2);
    for pair in s.as_bytes().chunks(2) {
        let hi = (pair[0] as char).to_digit(16)?;
        let lo = (pair[1] as char).to_digit(16)?;
        out.push((hi * 16 + lo) as u8);
    }
    Some(out)
}

pub fn sha256_hex(bytes: &[u8]) -> String {
    hex(&Sha256::digest(bytes))
}

fn now_epoch() -> i64 {
    SystemTime::now().duration_since(UNIX_EPOCH).map(|d| d.as_secs() as i64).unwrap_or(0)
}

fn random_hex(bytes: usize) -> Result<String, ProvisionError> {
    let mut buf = vec![0u8; bytes];
    getrandom::getrandom(&mut buf).map_err(|e| ProvisionError::Unsupported {
        platform: platform_name().to_string(),
        what: format!("the OS CSPRNG is unavailable, so no key material can be minted: {e}"),
    })?;
    Ok(hex(&buf))
}

/// 32 raw CSPRNG bytes for a seed, on the caller's own stack.
///
/// Deliberately NOT `random_hex` + `unhex`. That route put the seed through a heap
/// `String` and a heap `Vec`, neither of which anything owned by this module could
/// afterwards overwrite — for a key that is meant to be destroyed, every extra copy is a
/// copy the destruction does not reach. This returns the array, which the caller wipes.
fn random_seed() -> Result<[u8; 32], ProvisionError> {
    let mut seed = [0u8; 32];
    getrandom::getrandom(&mut seed).map_err(|e| ProvisionError::Unsupported {
        platform: platform_name().to_string(),
        what: format!("the OS CSPRNG is unavailable, so no key material can be minted: {e}"),
    })?;
    Ok(seed)
}

/// Overwrite a seed buffer, through a write the optimiser may not elide.
///
/// `ed25519_dalek::SigningKey` is `ZeroizeOnDrop` (the `zeroize` feature is on by
/// default in 2.x, and `Drop` calls `secret_key.zeroize()`), so the copy inside the key
/// is handled. This is for the array the seed arrived in, which dalek copies out of.
fn wipe(seed: &mut [u8; 32]) {
    for byte in seed.iter_mut() {
        // `write_volatile` is what stops a "this store is never read" pass from removing
        // the loop entirely; a plain `*byte = 0` on a local about to go out of scope is
        // exactly the store LLVM is allowed to drop.
        unsafe { std::ptr::write_volatile(byte, 0) };
    }
}

/// Every artifact type the engine binds to `authority`, sorted — the same set
/// `broctl._artifacts_for` computes from `ARTIFACT_AUTHORITY`.
pub fn artifacts_for(authority: &str) -> Vec<String> {
    let mut v: Vec<String> = ARTIFACT_AUTHORITY
        .iter()
        .filter(|(_, a)| *a == authority)
        .map(|(t, _)| t.to_string())
        .collect();
    v.sort();
    v
}

fn subject_agent_id(authority: &str) -> Option<&'static str> {
    match authority {
        BUILDER => Some(BUILDER_AGENT_ID),
        VERIFIER => Some(VERIFIER_AGENT_ID),
        _ => None,
    }
}

