#[derive(Debug)]
pub enum ProvisionError {
    Io { what: String, path: PathBuf, source: std::io::Error },
    Canonical(NonCanonical),
    /// The trust store on disk is present but does not verify. Never repaired and
    /// never re-minted over: a store that fails verification is either damaged or
    /// tampered with, and silently replacing it destroys the evidence of which.
    Corrupt { what: String, detail: String },
    /// This platform cannot do something the posture requires. Fails closed.
    Unsupported { platform: String, what: String },
    /// The trust anchor is not held where the policed account cannot write it — the one
    /// property O-2 reduces to. Raised by [`anchor::prove_unwritable`] with the path, the
    /// measurement that failed, and what a deployment has to change.
    ///
    /// Never softened into a warning and never given a fallback: a deployment that cannot
    /// provide the location has no trust anchor, and continuing without one would mean the
    /// application choosing its own trust root while reporting that it had one.
    Custody { path: PathBuf, what: String, remedy: String },
}

impl std::fmt::Display for ProvisionError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            ProvisionError::Io { what, path, source } => {
                write!(f, "trust provisioning failed while {what} ({}): {source}", path.display())
            }
            ProvisionError::Canonical(e) => write!(f, "trust provisioning failed: {e}"),
            ProvisionError::Corrupt { what, detail } => write!(
                f,
                "the provisioned trust store is not usable — {what}: {detail}. Nothing was \
                 changed or deleted. Move or remove the `trust` directory in the application \
                 data directory to have it re-minted from scratch."
            ),
            ProvisionError::Unsupported { platform, what } => {
                write!(f, "trust provisioning refuses to continue on {platform}: {what}")
            }
            ProvisionError::Custody { path, what, remedy } => write!(
                f,
                "the trust anchor at {} is not out of this account's reach — {what}. {remedy}",
                path.display()
            ),
        }
    }
}

impl std::error::Error for ProvisionError {}

impl From<NonCanonical> for ProvisionError {
    fn from(e: NonCanonical) -> Self {
        ProvisionError::Canonical(e)
    }
}

fn io<T>(r: std::io::Result<T>, what: &str, path: &Path) -> Result<T, ProvisionError> {
    r.map_err(|source| ProvisionError::Io {
        what: what.to_string(),
        path: path.to_path_buf(),
        source,
    })
}

fn corrupt<T>(what: &str, detail: impl Into<String>) -> Result<T, ProvisionError> {
    Err(ProvisionError::Corrupt { what: what.to_string(), detail: detail.into() })
}

