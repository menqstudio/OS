/// The `not_after_epoch` / `expires_at_epoch` every key and artifact this module mints
/// carries: 9999-12-31T23:59:59Z.
///
/// **The decision.** `broctl`'s `DEFAULT_VALIDITY_SECONDS` is one year, which is right
/// for a fleet whose operator re-signs a registry on a schedule and wrong here: this
/// product has no operator other than the person who installed it, and a desktop app
/// that stops working after a year until its owner "renews" something is exactly the
/// ceremony this design forbids. So validity is unbounded in the only way the schema
/// allows — `not_after_epoch` must be an int, so it is set to a date no clock reaches.
///
/// **What it costs.** Expiry can never be the mechanism that retires a compromised
/// key. Retirement has to come from re-minting the registry with that key marked
/// `revoked` and raising [`REGISTRY_VERSION`], which the anti-rollback floor
/// (`BRO_OPERATOR_REGISTRY_MIN_FILE`, written by this module) then makes stick — a
/// superseded but still operator-signed registry replayed from a backup is refused.
/// On a machine whose owner is the attacker, both the re-mint and the floor are
/// rewritable, which is the boundary stated at the top of this module and not a
/// property a one-year expiry would have restored.
pub const NEVER_EXPIRES_EPOCH: i64 = 253_402_300_799;

/// `not_before_epoch` for every minted key: the epoch.
///
/// Not "now". `verify_artifact` refuses a key whose `not_before_epoch` is in the
/// future, so stamping the install moment turns any backwards clock correction — a
/// machine that was ahead at install and got fixed by NTP an hour later — into a
/// governance chain that refuses everything until the clock catches up, with nothing
/// the user could do about it. A start-of-validity bound buys nothing here anyway:
/// the registry that introduces the key is itself the moment the key becomes real.
pub const NOT_BEFORE_EPOCH: i64 = 0;

/// The version stamped into the registry payload and written to the anti-rollback
/// floor file. A re-mint (revocation, added authority) must raise both together.
pub const REGISTRY_VERSION: i64 = 1;

