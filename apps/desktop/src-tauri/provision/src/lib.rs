/// The authorities whose PRIVATE half survives provisioning — everything in
/// [`MINTED_AUTHORITIES`] except `operator-root`.
///
/// # Why the root does not survive
///
/// The record of what happened must not be forgeable by the thing being recorded.
/// `bro_audit_log.verify_signed_payload` resolves an anchor's `key_id` through
/// `bro_signature.load_trusted_keys`, i.e. through the trusted-key registry — and the
/// registry is signed by `operator-root`. While this module left that private half in
/// `<app_data>/trust/keys/`, the app could mint an `audit-anchor` keypair of its own,
/// admit it to the registry, re-sign the registry, raise the anti-rollback floor it also
/// owns, and sign whatever head it liked. Narrowing `ANCHOR_AUTHORITIES` did not reach
/// that; nothing downstream can, because the registry's signer WAS the ledger's writer.
///
/// So the root is generated inside [`mint`], used for the two things only it may sign,
/// and destroyed. What the app legitimately needs afterwards was moved off it:
/// `control-room-command` (O-4) and `evidence-floor-anchor` (O-5) are bound to the
/// delegated `control-room` and `evidence-floor` authorities in
/// `bro_signature.ARTIFACT_AUTHORITY`, and those keys ARE retained. They may be: a
/// machine that is compromised can authorise its own control-room command and state its
/// own evidence high-water mark anyway. Neither can sign a `trusted-key-registry`, a
/// `conductor-session` or an `audit-head`, and the engine refuses each by name.
///
/// # What this does NOT close
///
/// The operator-root PIN (`pin/operator-root.pub`) and the anti-rollback floor still live
/// in the app's own data directory under `BRO_OPERATOR_ROOT_PIN_SELF_OWNED=acknowledged`.
/// An account that can rewrite the pin can install a trust root of its own and re-sign
/// everything under it, with no need for the destroyed key at all. That route is proved
/// open, by running it, in `audit-signer/tests/anchor_end_to_end.py`
/// (`case_pin_rewrite`). Destroying the root removes the KEY; it does not move the
/// ANCHOR out of the app's reach, and only a second principal can do that.
