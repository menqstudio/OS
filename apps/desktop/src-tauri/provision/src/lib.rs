/// Sign `payload` and wrap it as the `{payload, signature}` document every
/// `bro_signature` verifier accepts. The signature is Ed25519 over
/// [`canonical_bytes`] of the payload, hex-encoded exactly as `broctl.sign_payload`
/// writes it (`private.sign(canonical_bytes(payload)).hex()`).
pub fn sign_document(key: &SigningKey, payload: Value) -> Result<Value, ProvisionError> {
    let bytes = canonical_bytes(&payload)?;
    let signature = key.sign(&bytes);
    Ok(json!({"payload": payload, "signature": hex(&signature.to_bytes())}))
}

/// The Rust half of `bro_signature.verify_detached`, used only to re-check this
/// module's own output on a later launch.
fn verify_document(document: &Value, public_key_hex: &str) -> Result<Value, ProvisionError> {
    let payload = match document.get("payload") {
        Some(p) => p.clone(),
        None => return corrupt("a signed document has no payload", "missing `payload`"),
    };
    let sig_hex = match document.get("signature").and_then(|s| s.as_str()) {
        Some(s) => s,
        None => return corrupt("a signed document has no signature", "missing `signature`"),
    };
    let raw_key: [u8; 32] = match unhex(public_key_hex).map(<[u8; 32]>::try_from) {
        Some(Ok(k)) => k,
        _ => {
            return corrupt(
                "the operator-root public key is unusable",
                format!("expected 64 hex characters, got {public_key_hex:?}"),
            )
        }
    };
    let vk = match VerifyingKey::from_bytes(&raw_key) {
        Ok(k) => k,
        Err(e) => return corrupt("the operator-root public key is unusable", e.to_string()),
    };
    let raw_sig: [u8; 64] = match unhex(sig_hex).map(<[u8; 64]>::try_from) {
        Some(Ok(s)) => s,
        _ => {
            return corrupt(
                "a signature is malformed",
                format!("expected 128 hex characters, got {} characters", sig_hex.len()),
            )
        }
    };
    let sig = Signature::from_bytes(&raw_sig);
    let bytes = canonical_bytes(&payload)?;
    match vk.verify(&bytes, &sig) {
        Ok(()) => Ok(payload),
        Err(e) => {
            corrupt("a signature does not verify against the operator-root pin", e.to_string())
        }
    }
}

