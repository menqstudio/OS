fn write_bytes(path: &Path, bytes: &[u8]) -> Result<(), ProvisionError> {
    if let Some(parent) = path.parent() {
        io(std::fs::create_dir_all(parent), "creating a directory", parent)?;
    }
    let mut file = io(std::fs::File::create(path), "creating a file", path)?;
    io(file.write_all(bytes), "writing a file", path)?;
    io(file.sync_all(), "flushing a file", path)?;
    Ok(())
}

fn write_json(path: &Path, value: &Value) -> Result<(), ProvisionError> {
    let mut bytes = canonical_bytes(value)?;
    bytes.push(b'\n');
    write_bytes(path, &bytes)
}

/// Key material only: created with an owner-only mode where the platform has one, then
/// restricted again through [`secure_owner_only_file`] because the creation mode is
/// masked by the process umask. `create_new` refuses to clobber an existing key file —
/// silently replacing a signing key is a rotation, and rotations must never be
/// accidental (the rule `broctl._write_key` states).
fn write_key_file(path: &Path, value: &Value) -> Result<(), ProvisionError> {
    let mut bytes = canonical_bytes(value)?;
    bytes.push(b'\n');
    if let Some(parent) = path.parent() {
        io(std::fs::create_dir_all(parent), "creating the key directory", parent)?;
    }
    let mut options = std::fs::OpenOptions::new();
    options.write(true).create_new(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        options.mode(0o600);
    }
    let mut file = io(options.open(path), "creating a private key file", path)?;
    io(file.write_all(&bytes), "writing a private key file", path)?;
    io(file.sync_all(), "flushing a private key file", path)?;
    drop(file);
    io(secure_owner_only_file(path), "restricting a private key file to its owner", path)?;
    Ok(())
}

