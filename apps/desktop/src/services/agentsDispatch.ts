/** The Tauri command a governed dispatch would go through. Not registered in this build. */
export const DISPATCH_COMMAND = 'dispatch_task_contract';
export const DISPATCH_REQUEST_PROTOCOL = 'brops.agent-dispatch.v1';
export const DISPATCH_RESULT_PROTOCOL = 'brops.agent-dispatch-result.v1';
/** A payload that carries NO contract, so no conforming backend can mistake it for a dispatch. */
export const DISPATCH_PROBE_PROTOCOL = 'brops.agent-dispatch-probe.v1';

/**
 * What `apps/desktop/src-tauri` must add before a dispatch can be anything but
 * `unreachable`. Written here because the surface quotes it verbatim: a page that says
 * "not wired" without saying what is missing is just a shrug.
 */
export const DISPATCH_REQUIREMENT = [
  `a \`${DISPATCH_COMMAND}\` Tauri command in apps/desktop/src-tauri`,
  'which seals the repository block (full_name, branch, worktree, base_commit, tree_identity) from the real worktree',
  'hands the sealed contract to the engine supervisor for a lease',
  `and replies with protocol '${DISPATCH_RESULT_PROTOCOL}' carrying the assignment id, the contract digest and that sealed block`,
].join(', ');

/** The CLOSED set of reasons a backend may refuse a dispatch. Anything else is not a refusal. */
export const DISPATCH_REFUSALS = [
  'malformed_contract', 'unknown_agent', 'unknown_pack', 'scope_denied',
  'authority_denied', 'risk_ceiling_exceeded', 'verifier_denied', 'no_lease',
] as const;
export type DispatchRefusal = (typeof DISPATCH_REFUSALS)[number];

export interface DispatchRequest {
  protocol: typeof DISPATCH_REQUEST_PROTOCOL;
  client_request_id: string;
  /** The definition that is actually spawned — always a tier, because a tier is the only
   *  thing whose tool list bounds anything. */
  agent_definition: CapabilityTier;
  capability_tier: CapabilityTier;
  /** Advisory: the pack-role definition consulted for specialism + authority. The backend
   *  may log or check it, but it is not what contains the specialist. */
  pack_role_reference: string | null;
  contract_draft: ContractDraft;
}

export interface ProbeRequest {
  protocol: typeof DISPATCH_PROBE_PROTOCOL;
  client_request_id: string;
}

/**
 * The honest outcomes. `accepted` is the ONLY one that may be rendered as a real dispatch,
 * and it is reachable solely from a well-formed backend reply.
 */
export type DispatchOutcome =
  | { state: 'invalid'; problems: Problem[] }
  | { state: 'unreachable'; reason: string }
  | { state: 'refused'; clientRequestId: string; reason: DispatchRefusal; detail: string | null }
  | {
      state: 'accepted';
      clientRequestId: string;
      assignmentId: string;
      contractDigest: string;
      leaseId: string;
      repository: RepositoryBinding;
    };

export type DispatchTransport = (request: DispatchRequest | ProbeRequest) => Promise<unknown>;
export type IdGen = () => string;

const UUIDV4 = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;

function rec(v: unknown): Record<string, unknown> | null {
  return typeof v === 'object' && v !== null && !Array.isArray(v) ? (v as Record<string, unknown>) : null;
}
function s(o: Record<string, unknown>, k: string): string | null {
  const v = o[k];
  return typeof v === 'string' && v.length > 0 ? v : null;
}

function parseRepository(v: unknown): RepositoryBinding | null {
  const o = rec(v);
  if (!o) return null;
  const full_name = s(o, 'full_name');
  const branch = s(o, 'branch');
  const worktree = s(o, 'worktree');
  const base_commit = s(o, 'base_commit');
  const tree_identity = s(o, 'tree_identity');
  if (!full_name || !branch || !worktree || !base_commit || !tree_identity) return null;
  // The two identity fields are the whole point of the block: a repository binding whose
  // commit/tree are not real digests binds nothing, so it is not a binding.
  if (!SHA1_HEX.test(base_commit) || !SHA256_HEX.test(tree_identity)) return null;
  return { full_name, branch, worktree, base_commit, tree_identity };
}

/**
 * Parse a backend reply FAIL-CLOSED. It will never upgrade an unknown, partial or
 * odd reply into `accepted`; anything it cannot fully authenticate as an accepted or
 * refused frame becomes `unreachable` with the reason it failed on.
 */
export function parseDispatchReply(raw: unknown): DispatchOutcome {
  const o = rec(raw);
  if (!o) return { state: 'unreachable', reason: 'dispatch reply was not an object' };
  if (o.protocol !== DISPATCH_RESULT_PROTOCOL) {
    return { state: 'unreachable', reason: `dispatch reply has the wrong protocol: ${String(o.protocol)}` };
  }
  const clientRequestId = s(o, 'client_request_id');
  if (!clientRequestId) return { state: 'unreachable', reason: 'dispatch reply has no client_request_id to correlate' };

  if (o.status === 'accepted') {
    if ('reason' in o) return { state: 'unreachable', reason: 'an accepted frame must not carry a refusal reason' };
    const assignmentId = s(o, 'assignment_id');
    const contractDigest = s(o, 'contract_digest');
    const leaseId = s(o, 'lease_id');
    const repository = parseRepository(o.repository);
    if (!assignmentId) return { state: 'unreachable', reason: 'accepted frame has no assignment_id' };
    if (!contractDigest || !SHA256_HEX.test(contractDigest)) {
      return { state: 'unreachable', reason: 'accepted frame has no sha256 contract_digest — nothing pins what was accepted' };
    }
    if (!leaseId) {
      return { state: 'unreachable', reason: 'accepted frame has no lease_id — an assignment without a lease was not governed' };
    }
    if (!repository) {
      return { state: 'unreachable', reason: 'accepted frame has no sealed repository binding — the contract the engine took is not identified' };
    }
    return { state: 'accepted', clientRequestId, assignmentId, contractDigest, leaseId, repository };
  }

  if (o.status === 'refused') {
    const reason = o.reason;
    if (typeof reason !== 'string' || !(DISPATCH_REFUSALS as readonly string[]).includes(reason)) {
      return { state: 'unreachable', reason: `refusal reason is outside the closed set: ${String(reason)}` };
    }
    return { state: 'refused', clientRequestId, reason: reason as DispatchRefusal, detail: s(o, 'detail') };
  }

  return { state: 'unreachable', reason: `unknown dispatch status ${String(o.status)}` };
}

/**
 * Attempt one governed dispatch.
 *
 * Order matters: the draft is validated FIRST and a failing draft is never sent. The
 * renderer refusing to transmit a malformed contract is not a substitute for engine
 * validation — the engine validates again — it just means the renderer does not ask for
 * something it already knows is wrong.
 */
export async function attemptDispatch(
  assignment: Assignment,
  transport: DispatchTransport,
  genId: IdGen,
): Promise<DispatchOutcome> {
  const problems = validateAssignment(assignment);
  if (problems.length > 0) return { state: 'invalid', problems };

  const clientRequestId = genId();
  if (!UUIDV4.test(clientRequestId)) {
    return { state: 'unreachable', reason: 'client_request_id must be a lowercase UUIDv4' };
  }

  const request: DispatchRequest = {
    protocol: DISPATCH_REQUEST_PROTOCOL,
    client_request_id: clientRequestId,
    agent_definition: assignment.grant.tier,
    capability_tier: assignment.grant.tier,
    pack_role_reference: assignment.grant.packRole,
    contract_draft: assignment.draft,
  };

  let raw: unknown;
  try {
    raw = await transport(request);
  } catch (e) {
    return { state: 'unreachable', reason: e instanceof Error ? e.message : String(e) };
  }
  const outcome = parseDispatchReply(raw);
  if (outcome.state === 'accepted' && outcome.clientRequestId !== clientRequestId) {
    return { state: 'unreachable', reason: 'accepted frame does not correlate with this request' };
  }
  return outcome;
}

/** Whether the dispatch channel exists at all. `present` says nothing about acceptance. */
export type ChannelState =
  | { state: 'present'; detail: string }
  | { state: 'absent'; reason: string };

/**
 * Ask, live, whether a dispatch channel exists. Sends a probe frame that carries NO
 * contract, so it cannot be mistaken for a dispatch by any backend that reads its own
 * protocol field. A rejection (command not registered, no Tauri runtime, IPC error) is the
 * honest `absent`; ANY resolution means something answered on that command — which is all
 * `present` claims.
 */
export async function probeDispatchChannel(transport: DispatchTransport, genId: IdGen): Promise<ChannelState> {
  if (!hasBackend()) {
    return { state: 'absent', reason: 'no Tauri runtime — this window has no IPC to a backend at all' };
  }
  try {
    const reply = await transport({ protocol: DISPATCH_PROBE_PROTOCOL, client_request_id: genId() });
    const o = rec(reply);
    return {
      state: 'present',
      detail: o && typeof o.protocol === 'string'
        ? `the command answered with protocol ${o.protocol}`
        : 'the command answered; the reply carried no protocol',
    };
  } catch (e) {
    return { state: 'absent', reason: e instanceof Error ? e.message : String(e) };
  }
}

/** A UUIDv4 from the platform CSPRNG. Never falls back to a weak id — a value that fails
 *  the UUIDv4 check makes `attemptDispatch` refuse rather than send something
 *  uncorrelatable. */
export const uuid: IdGen = () =>
  (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function' ? crypto.randomUUID() : 'unavailable');

/** The real transport: `invoke(DISPATCH_COMMAND, …)`. Rejects in this build — no such command. */
export function tauriDispatchTransport(): DispatchTransport {
  return async (request) => {
    const { invoke } = await import('@tauri-apps/api/core');
    return invoke<unknown>(DISPATCH_COMMAND, { request });
  };
}

/**
 * Stable, readable JSON of what would go over the wire — the thing the surface shows.
 * The two capability fields are labelled by what they DO, so a reader of the preview
 * cannot come away thinking the pack role is the containment.
 */
export function previewJson(assignment: Assignment): string {
  return JSON.stringify(
    {
      enforced_capability: {
        agent_definition: assignment.grant.tier,
        tools: assignment.grant.tools,
        source: assignment.grant.tierDefinitionPath,
      },
      advisory_pack_role: assignment.grant.packRole
        ? { reference: assignment.grant.packRole, source: assignment.grant.packRolePath,
            note: 'read for specialism and authority; not enforced' }
        : null,
      contract_draft: assignment.draft,
      repository: '<sealed by the engine at dispatch — the desktop cannot observe it>',
    },
    null,
    2,
  );
}
