// Phase-6 (Multi-Agent) — renderer-side GOVERNED DISPATCH composer.
//
// What this module is for
// -----------------------
// Before it existed, the Agents/Tasks surfaces could show a roster and a board but had
// no way to hand a task to an agent under the authority contract: there was no dispatch
// at all, governed or otherwise. This module builds the thing that would be dispatched —
// a real, contract-shaped assignment — and attempts to hand it to the engine.
//
// The owner's model, restated as code — and note carefully WHICH half is enforced:
//
//   * The CAPABILITY half is the TIER, and only the tier. `apps/desktop/src-tauri/src/ai.rs`
//     passes the three tiers (`reader`, `runner`, `builder`) to the CLI inline via
//     `--agents`, and that tool list is the only thing that actually bounds what a
//     specialist can do. Bro spawns a TIER.
//   * The 262 pack-role definitions in `.claude/agents/` (generated by
//     `tools/generate_agent_definitions.py` from `engine/packs/registry.json` +
//     `engine/agents/authority-policy.json`) are READ — to decide the specialism and which
//     authority record it falls under — and then Bro spawns the matching tier. A pack role
//     is a REFERENCE, not an enforcement point, and this module must never imply otherwise:
//     `CapabilityGrant.packRole` is explicitly advisory, `CapabilityGrant.tier` is what
//     binds. Painting a pack role as the thing that contains a specialist would be exactly
//     the decorative-authority problem the generated definitions were written to end.
//   * The PATH half is a property of the JOB. It lives in the task contract as `scope` and
//     `prohibited_scope` (`engine/schemas/task-contract.schema.json`).
//
// So one assignment = one enforced tier + one advisory pack-role reference + one contract
// draft (paths, risk, mode, verifier). Bro decides WHO gets WHAT capability at WHICH path.
//
// What this module is NOT
// -----------------------
// It is not the engine, and it never speaks for it.
//
//   1. `validateAssignment` is a PRE-FLIGHT refusal, not an acceptance. It mirrors the
//      engine schema's rules so an obviously-bad draft never leaves the renderer, and it
//      can only ever say NO. A draft with zero problems is "locally well-formed", which is
//      strictly weaker than "the engine accepted it". The UI must never conflate the two.
//   2. The draft is deliberately INCOMPLETE. `engine/schemas/task-contract.schema.json`
//      requires a `repository` block with `base_commit` (40 hex) and `tree_identity`
//      (64 hex). Those are host facts about a real git worktree; the desktop has no IPC
//      that can observe them and MUST NOT invent them. The engine seals that block at
//      dispatch time and echoes it back — see `RepositoryBinding` and `DISPATCH_REQUIREMENT`.
//   3. Only a well-formed `accepted` reply from the backend is ever reported as accepted.
//      Every other reply — malformed, unknown, thrown, absent command, no Tauri runtime —
//      degrades to `refused` or `unreachable`. There is no path from a missing backend to
//      a green state.
//
// Today no such backend command exists (`apps/desktop/src-tauri` registers no dispatch
// command), so a real attempt resolves to `unreachable` with the transport's own reason.
// That is the honest outcome and the surface says exactly that instead of pretending.

import { hasBackend } from './desktop';

