/** `schema` const in the task-contract schema. */
export const CONTRACT_SCHEMA_VERSION = 1;
/** The single normative source these rules mirror. Quoted in the UI so a reader can check. */
export const CONTRACT_SCHEMA_SOURCE = 'engine/schemas/task-contract.schema.json';
/** The authority record source. */
export const AUTHORITY_POLICY_SOURCE = 'engine/agents/authority-policy.json';
/** Where the capability half of a grant is declared. */
export const AGENT_DEFINITION_DIR = '.claude/agents';

export const MODES = ['review', 'work', 'release'] as const;
export type Mode = (typeof MODES)[number];

export const RISKS = ['low', 'medium', 'high', 'critical'] as const;
export type Risk = (typeof RISKS)[number];

/** Rank of a risk level, in the order `authority-policy.json.risk_order` declares. */
export function riskRank(r: Risk): number {
  return RISKS.indexOf(r);
}

// ─────────────────────────────────────────────────────────────────────────────
// 2. Capability tiers — mirrored from tools/generate_agent_definitions.py TIERS
