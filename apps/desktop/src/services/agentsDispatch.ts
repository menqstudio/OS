export interface Verification {
  required: boolean;
  verifier_agent_id: string | null;
  verifier_role: string | null;
  commands: string[];
}

export interface Rollback {
  strategy: string;
  commands: string[];
}

/**
 * The `repository` block of a complete task contract. The desktop CANNOT produce this:
 * `base_commit` and `tree_identity` are facts about a real worktree at a real instant, and
 * inventing them would make a contract that reads authoritative and binds nothing. The
 * engine seals it at dispatch and echoes it in the accepted reply, which is why it appears
 * here only as an OUTPUT type.
 */
export interface RepositoryBinding {
  full_name: string;
  branch: string;
  worktree: string;
  base_commit: string;
  tree_identity: string;
}

const SHA1_HEX = /^[0-9a-f]{40}$/;
const SHA256_HEX = /^[0-9a-f]{64}$/;

/**
 * Everything a task contract requires EXCEPT `repository`. Field names are the schema's
 * snake_case on purpose: this object is the wire body, not a view model, and a rename
 * between here and the engine is exactly the kind of drift that makes a contract decorative.
 */
export interface ContractDraft {
  schema: typeof CONTRACT_SCHEMA_VERSION;
  task_id: string;
  title: string;
  objective: string;
  mode: Mode;
  risk: Risk;
  pack_id: string;
  agent_id: string;
  assignee_role: string;
  scope: string[];
  prohibited_scope: string[];
  inputs: string[];
  core_skills: string[];
  additional_skills: string[];
  reference_skills: string[];
  done_criteria: string[];
  verification: Verification;
  rollback: Rollback;
}

/**
 * The capability half of the grant, split by what is actually enforced.
 *
 * `tier` BINDS: it is the definition Bro spawns, and `ai.rs` hands its tool list to the
 * CLI inline via `--agents`. `packRole` DOES NOT bind: it names the generated pack-role
 * definition that was consulted for the specialism and its authority record. Keeping the
 * two fields apart — rather than one vague `definition` — is the point, because a surface
 * that shows a pack role as the grant would be claiming containment that does not exist.
 */
export interface CapabilityGrant {
  /** ENFORCED. The tier Bro spawns; its tool list is the real bound. */
  tier: CapabilityTier;
  /** ENFORCED. Exactly the tools that tier's definition declares. */
  tools: readonly string[];
  /** The file that decides those tools, so the claim is checkable. */
  tierDefinitionPath: string;
  /** ADVISORY. The consulted pack-role definition (`<pack>--<role>`), or null when the
   *  pack/role are not both stated. Read for specialism + authority; never enforced. */
  packRole: string | null;
  /** ADVISORY. Where that definition lives, so a reader can check what it claims. */
  packRolePath: string | null;
}

/** One capability grant + one contract draft. This is what "a dispatch" means. */
export interface Assignment {
  grant: CapabilityGrant;
  draft: ContractDraft;
}

/** A validation refusal. `field` is the contract path it belongs to. */
export interface Problem {
  field: string;
  message: string;
}

export interface AssignmentInput {
  taskId: string;
  title: string;
  objective: string;
  mode: Mode;
  risk: Risk;
  packId: string;
  /** The agent's slug (or id) — becomes `agent_id` in contract-id form. */
  agentSlug: string;
  assigneeRole: string;
  tier: CapabilityTier;
  scope: string[];
  prohibitedScope: string[];
  inputs?: string[];
  coreSkills: string[];
  additionalSkills?: string[];
  referenceSkills?: string[];
  doneCriteria: string[];
  verifierAgentSlug: string | null;
  verifierRole: string | null;
  verificationCommands: string[];
  rollbackStrategy: string;
  rollbackCommands?: string[];
}

/**
 * Build the assignment. Pure and total: it never throws and never silently repairs an
 * input. A field the caller gave badly stays bad and `validateAssignment` reports it —
 * quietly fixing a malformed id here would hide the very thing the contract exists to pin.
 */
export function buildAssignment(input: AssignmentInput): Assignment {
  const agentId = slug(input.agentSlug);
  const verifierId = input.verifierAgentSlug ? slug(input.verifierAgentSlug) : null;
  const required = verifierIsMandatory(input.risk) || verifierId !== null;
  // The advisory reference resolves only when both halves of the name are really stated.
  // Half a name would point at no file, and a dangling reference reads as an authority.
  const packRole = input.packId.trim() && input.assigneeRole.trim()
    ? packRoleDefinitionName(input.packId, input.assigneeRole)
    : null;
  return {
    grant: {
      tier: input.tier,
      tools: TIER_TOOLS[input.tier],
      tierDefinitionPath: `${AGENT_DEFINITION_DIR}/${input.tier}.md`,
      packRole,
      packRolePath: packRole ? `${AGENT_DEFINITION_DIR}/${packRole}.md` : null,
    },
    draft: {
      schema: CONTRACT_SCHEMA_VERSION,
      task_id: slug(input.taskId),
      title: input.title,
      objective: input.objective,
      mode: input.mode,
      risk: input.risk,
      pack_id: slug(input.packId),
      agent_id: agentId,
      assignee_role: input.assigneeRole,
      scope: input.scope,
      prohibited_scope: input.prohibitedScope,
      inputs: input.inputs ?? [],
      core_skills: input.coreSkills,
      additional_skills: input.additionalSkills ?? [],
      reference_skills: input.referenceSkills ?? [],
      done_criteria: input.doneCriteria,
      verification: {
        required,
        verifier_agent_id: verifierId,
        verifier_role: input.verifierRole,
        commands: input.verificationCommands,
      },
      rollback: {
        strategy: input.rollbackStrategy,
        commands: input.rollbackCommands ?? [],
      },
    },
  };
}

function dupes(list: readonly string[]): string[] {
  const seen = new Set<string>();
  const out = new Set<string>();
  for (const v of list) {
    if (seen.has(v)) out.add(v);
    seen.add(v);
  }
  return [...out];
}

function checkIdList(list: readonly string[], field: string, problems: Problem[]): void {
  for (const id of list) {
    if (!isContractId(id)) {
      problems.push({ field, message: `'${id}' is not a valid contract id (^[a-z0-9][a-z0-9._-]{1,127}$)` });
    }
  }
  for (const d of dupes(list)) problems.push({ field, message: `'${d}' is listed twice; entries must be unique` });
}

/**
 * Pre-flight refusal. Returns every problem found — an empty array means "locally
 * well-formed", NOT "accepted". Ordered checks: shape (what the schema requires), then
 * authority (what the default record permits), then coherence (a grant that contradicts
 * itself). Each message says what is wrong AND why the rule exists, because a refusal a
 * person cannot act on just gets worked around.
 */
export function validateAssignment(a: Assignment): Problem[] {
  const p: Problem[] = [];
  const d = a.draft;

  // — shape —
  if (d.schema !== CONTRACT_SCHEMA_VERSION) {
    p.push({ field: 'schema', message: `schema must be ${CONTRACT_SCHEMA_VERSION}` });
  }
  for (const [field, value] of [['task_id', d.task_id], ['pack_id', d.pack_id], ['agent_id', d.agent_id]] as const) {
    if (!isContractId(value)) {
      p.push({ field, message: value ? `'${value}' is not a valid contract id` : 'is required' });
    }
  }
  if (!d.title.trim()) p.push({ field: 'title', message: 'is required' });
  if (!d.objective.trim()) p.push({ field: 'objective', message: 'is required — the agent is told this, not the UI label' });
  if (!d.assignee_role.trim()) p.push({ field: 'assignee_role', message: 'is required' });
  if (!MODES.includes(d.mode)) p.push({ field: 'mode', message: `must be one of ${MODES.join(', ')}` });
  if (!RISKS.includes(d.risk)) p.push({ field: 'risk', message: `must be one of ${RISKS.join(', ')}` });

  if (d.scope.length === 0) {
    p.push({ field: 'scope', message: 'at least one path is required — a task with no scope grants nothing and is not a grant' });
  }
  for (const s of d.scope) {
    if (!isWorkPath(s)) p.push({ field: 'scope', message: `'${s}' is not a valid work path (no '..', no backslash, no ':', no glob, no bare root)` });
  }
  for (const dup of dupes(d.scope)) p.push({ field: 'scope', message: `'${dup}' is listed twice; entries must be unique` });
  for (const s of d.prohibited_scope) {
    if (!isWorkPath(s)) p.push({ field: 'prohibited_scope', message: `'${s}' is not a valid work path` });
  }
  for (const dup of dupes(d.prohibited_scope)) p.push({ field: 'prohibited_scope', message: `'${dup}' is listed twice; entries must be unique` });
  for (const s of d.inputs) {
    if (!isRepoPath(s)) p.push({ field: 'inputs', message: `'${s}' must be a path relative to this checkout` });
  }

  if (d.core_skills.length === 0) {
    p.push({
      field: 'core_skills',
      message: 'at least one skill id is required. The desktop has no IPC that lists engine/skills, so it cannot fill this in — state the ids the task really needs',
    });
  }
  checkIdList(d.core_skills, 'core_skills', p);
  checkIdList(d.additional_skills, 'additional_skills', p);
  checkIdList(d.reference_skills, 'reference_skills', p);

  if (d.done_criteria.length === 0) {
    p.push({ field: 'done_criteria', message: 'at least one criterion is required — otherwise nobody can say the task finished' });
  }
  if (!d.rollback.strategy.trim()) {
    p.push({ field: 'rollback.strategy', message: 'is required — a grant with no way back is not reversible' });
  }

  // — authority (default record only; the desktop cannot read an override) —
  if (!DEFAULT_AUTHORITY.allowed_modes.includes(d.mode)) {
    p.push({
      field: 'mode',
      message: `'${d.mode}' is outside the default authority (${DEFAULT_AUTHORITY.allowed_modes.join(', ')}). Only a declared exact override in ${AUTHORITY_POLICY_SOURCE} grants it, and the desktop cannot read that record — so it refuses rather than assumes`,
    });
  }
  if (riskRank(d.risk) > riskRank(DEFAULT_AUTHORITY.risk_ceiling)) {
    p.push({
      field: 'risk',
      message: `'${d.risk}' exceeds the default risk ceiling '${DEFAULT_AUTHORITY.risk_ceiling}'. Raising it needs an authority record the desktop cannot read`,
    });
  }

  // — verification —
  const v = d.verification;
  if (verifierIsMandatory(d.risk) && !v.required) {
    p.push({
      field: 'verification.required',
      message: `risk '${d.risk}' requires independence ${INDEPENDENCE_MINIMUM_BY_RISK[d.risk]} — verification cannot be optional`,
    });
  }
  if (v.required) {
    if (!v.verifier_agent_id || !isContractId(v.verifier_agent_id)) {
      p.push({ field: 'verification.verifier_agent_id', message: 'a required verification needs a named verifier' });
    } else if (v.verifier_agent_id === d.agent_id) {
      p.push({
        field: 'verification.verifier_agent_id',
        message: 'the assignee cannot verify its own work — that is what independence means',
      });
    }
    if (!v.verifier_role || !v.verifier_role.trim()) {
      p.push({ field: 'verification.verifier_role', message: "a required verification needs the verifier's role" });
    }
    if (v.commands.length === 0) {
      p.push({
        field: 'verification.commands',
        message: 'a verifier that runs nothing can only opine — state the commands whose output is the evidence',
      });
    }
  }

  // — coherence of the grant itself —
  for (const s of d.scope) {
    const killer = d.prohibited_scope.find((x) => pathCovers(x, s));
    if (killer) {
      p.push({
        field: 'prohibited_scope',
        message: `'${killer}' covers the whole of scope entry '${s}' — this grant permits nothing`,
      });
    }
  }
  // A rollback plan handed to a tier that cannot change files means either the tier or
  // the intent is wrong. Stated rather than hidden: it is the common mistake.
  if (!TIER_CAN_WRITE[a.grant.tier] && d.rollback.commands.length > 0) {
    p.push({
      field: 'grant.tier',
      message: `tier '${a.grant.tier}' cannot change files, yet the draft declares rollback commands — either the tier or the intent is wrong`,
    });
  }

  return p;
}

/** `true` only when the draft cleared every pre-flight check. Still not acceptance. */
export function isLocallyWellFormed(a: Assignment): boolean {
  return validateAssignment(a).length === 0;
}

