export const CAPABILITY_TIERS = ['reader', 'runner', 'builder'] as const;
export type CapabilityTier = (typeof CAPABILITY_TIERS)[number];

/** The exact tool list each tier's generated definition declares. */
export const TIER_TOOLS: Record<CapabilityTier, readonly string[]> = {
  reader: ['Read', 'Grep', 'Glob'],
  runner: ['Read', 'Grep', 'Glob', 'Bash'],
  builder: ['Read', 'Edit', 'Write', 'Grep', 'Glob', 'Bash'],
};

/** Can the tier CHANGE files? Only `builder` can. */
export const TIER_CAN_WRITE: Record<CapabilityTier, boolean> = {
  reader: false, runner: false, builder: true,
};
/** Can the tier RUN anything (build, test, git inspection)? */
export const TIER_CAN_RUN: Record<CapabilityTier, boolean> = {
  reader: false, runner: true, builder: true,
};

// ─────────────────────────────────────────────────────────────────────────────
// 3. Authority — the DEFAULT record, and only the default
// ─────────────────────────────────────────────────────────────────────────────
//
// `authority-policy.json` has a default record, a designated-verifier record, and exact
// per-(pack, role) overrides. The desktop has no IPC that can read which record applies to
// a given agent, so it applies the DEFAULT and can only REFUSE beyond it. It never grants
// an override it cannot prove: a `release` mode or a `critical` risk is refused here with
// a reason that names the missing proof, not silently allowed.

export const DEFAULT_AUTHORITY = {
  can_build: true,
  can_verify: false,
  can_release: false,
  allowed_modes: ['review', 'work'] as readonly Mode[],
  risk_ceiling: 'high' as Risk,
} as const;

/** `authority-policy.json.independence_minimum_by_risk`. */
export const INDEPENDENCE_MINIMUM_BY_RISK: Record<Risk, string> = {
  low: 'L1', medium: 'L1', high: 'L2', critical: 'L3',
};

/** Risk levels at which an independent verifier is not optional (L2+). */
export function verifierIsMandatory(risk: Risk): boolean {
  return riskRank(risk) >= riskRank('high');
}

// ─────────────────────────────────────────────────────────────────────────────
// 4. Path grammar — the SAME patterns the schema's $defs declare
// ─────────────────────────────────────────────────────────────────────────────
//
// Copied literally from `task-contract.schema.json` $defs.repoPath / $defs.absolutePath.
// Segment rule: no empty / '.' / '..' segment, no leading or trailing whitespace, no
// backslash, no ':', no glob metacharacter, no NUL. A scope must be provably literal.
//
// DRIFT WARNING: these are a mirror. If the schema changes, this changes with it, and
// `agentsDispatch.test.ts` pins the corpus that proves the two agree on the cases that
// matter. A mirror that has drifted is worse than none — but it can only ever refuse
// MORE than the engine, never accept more, because the engine re-validates everything.

const ID_PATTERN = /^[a-z0-9][a-z0-9._-]{1,127}$/;
const REPO_PATH_PATTERN =
  /^(?:\.|(?!~)(?!\.\.?(?:\/|$))[^\s\\/:*?[\x00](?:[^\\/:*?[\x00]*[^\s\\/:*?[\x00])?(?:\/(?!\.\.?(?:\/|$))[^\s\\/:*?[\x00](?:[^\\/:*?[\x00]*[^\s\\/:*?[\x00])?)*)$/;
const ABSOLUTE_PATH_PATTERN =
  /^(?:\/|[A-Za-z]:\/)(?!\.\.?(?:\/|$))[^\s\\/:*?[\x00](?:[^\\/:*?[\x00]*[^\s\\/:*?[\x00])?(?:\/(?!\.\.?(?:\/|$))[^\s\\/:*?[\x00](?:[^\\/:*?[\x00]*[^\s\\/:*?[\x00])?)*$/;

/** A `$defs.id` — task_id, pack_id, agent_id, every skill id. */
export function isContractId(v: string): boolean {
  return ID_PATTERN.test(v);
}
/** A `$defs.repoPath` — relative to this checkout. `inputs` entries must be this. */
export function isRepoPath(v: string): boolean {
  return REPO_PATH_PATTERN.test(v);
}
/** A `$defs.absolutePath` — POSIX `/x` or Windows `C:/x`, forward slashes only. */
export function isAbsolutePath(v: string): boolean {
  return ABSOLUTE_PATH_PATTERN.test(v);
}
/** A `$defs.workPath` — where a task may act: repo-relative OR absolute. */
export function isWorkPath(v: string): boolean {
  return isRepoPath(v) || isAbsolutePath(v);
}

/**
 * `parent` covers `child` in the containment sense the enforcement layer uses:
 * the same entry, or a path beneath it. `.` is the repository root entry and covers
 * every repo-relative path (but no absolute one).
 *
 * This is a SYNTACTIC test only. Real containment is decided at use time by
 * `bro_security.enforce_scope`, which resolves symlinks and `..` first. It is used here
 * for one narrow purpose: to catch a grant that contradicts itself.
 */
export function pathCovers(parent: string, child: string): boolean {
  if (parent === child) return true;
  if (parent === '.') return isRepoPath(child) && child !== '.';
  return child.startsWith(`${parent}/`);
}

/** Split a textarea into path/id entries: one per line, blanks dropped, order kept. */
export function splitLines(text: string): string[] {
  return text.split(/\r?\n/).map((l) => l.trim()).filter((l) => l.length > 0);
}

/**
 * The slug function `tools/generate_agent_definitions.py` uses to name a definition file.
 * Kept identical in behaviour so a name derived here resolves to a real file.
 */
export function slug(text: string): string {
  return text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
}

/** `<pack-slug>--<role-slug>` — the generated pack-role definition name. */
export function packRoleDefinitionName(packId: string, role: string): string {
  return `${slug(packId)}--${slug(role)}`;
}

